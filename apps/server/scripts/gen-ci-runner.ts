// Writes the CI runner that runs inside workspaces (docs/prd/local-git-ci.md §11.1): images/workspace/cp-ci, which the
// workspace image bakes in for Kubernetes, and src/ci/runner.generated.ts, the same text for the portal to install into
// Docker workspaces. Run this after changing anything under src/ci/runner/ and commit both results
// (src/ci/runner/runner.test.ts fails until then): npm run gen:ci-runner -w @portal/server
import { chmodSync, writeFileSync } from 'node:fs';
import { buildRunner } from '../src/ci/runner/build.js';
import { config } from '../src/config.js';

const text = buildRunner();
const image = `${config.workspaces.imageContext}/cp-ci`;
writeFileSync(image, text);
chmodSync(image, 0o755);
const generated = new URL('../src/ci/runner.generated.ts', import.meta.url);
writeFileSync(
  generated,
  `// Generated by \`npm run gen:ci-runner -w @portal/server\` from src/ci/runner/. Do not edit: src/ci/runner/runner.test.ts keeps it equal to the source.\nexport const CP_CI = ${JSON.stringify(text)};\n`,
);
console.log(`Wrote ${image} and src/ci/runner.generated.ts (${text.length} bytes)`);
