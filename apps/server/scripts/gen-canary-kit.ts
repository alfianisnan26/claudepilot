// Writes src/claudeversion/canary/kit.generated.ts: the MCP stand-in provider (src/mcp/builtin/testkit) as one script, so the compatibility
// canary can run it inside its throwaway container without esbuild at run time (docs/prd/claude-version-pinning.md §11). Run it after changing
// anything under src/mcp/builtin/testkit/ and commit the result (src/claudeversion/claudeversion.test.ts fails until then):
//   npm run gen:canary-kit -w @portal/server
import { writeFileSync } from 'node:fs';
import { buildStandalone } from '../src/mcp/builtin/testkit/build.js';

const text = buildStandalone();
const generated = new URL('../src/claudeversion/canary/kit.generated.ts', import.meta.url);
writeFileSync(
  generated,
  `// Generated by \`npm run gen:canary-kit -w @portal/server\` from src/mcp/builtin/testkit/. Do not edit: src/claudeversion/claudeversion.test.ts keeps it equal to the source.\nexport const MCP_STANDIN = ${JSON.stringify(text)};\n`,
);
console.log(`Wrote src/claudeversion/canary/kit.generated.ts (${text.length} bytes)`);
