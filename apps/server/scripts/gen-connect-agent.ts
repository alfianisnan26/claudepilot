// Writes the agent bundle the portal serves (docs/prd/targets-connect.md §11.1): src/connect/agent.generated.ts, the same text as a string
// constant (PILOT_AGENT) with its SHA-256 and its build id (the first 12 hex), so it rides inside the server's own bundle: no Dockerfile
// change, no new package. Run this after changing anything the bundle is built from (src/connect/agent/**, src/connect/tunnel/**, the
// contract's connect.ts, workspaces/hostexec.ts) and commit the result: src/connect/agent/build.test.ts fails until it matches.
//   npm run gen:connect-agent -w @portal/server
import { writeFileSync } from 'node:fs';
import { buildAgent } from '../src/connect/agent/build.js';

const bundle = buildAgent();
const target = new URL('../src/connect/agent.generated.ts', import.meta.url);
writeFileSync(
  target,
  [
    '// Generated by `npm run gen:connect-agent -w @portal/server` from src/connect/agent/ and src/connect/tunnel/. Do not edit:',
    '// src/connect/agent/build.test.ts keeps it equal to a fresh build. PILOT_AGENT is the exact text of agent.mjs; the build id is the first',
    '// 12 hex of its SHA-256, which is also what the running agent reports as `agentBuild` (it hashes its own file).',
    `export const PILOT_AGENT = ${JSON.stringify(bundle.text)};`,
    `export const PILOT_AGENT_SHA256 = ${JSON.stringify(bundle.sha256)};`,
    `export const PILOT_AGENT_BUILD = ${JSON.stringify(bundle.build)};`,
    '',
  ].join('\n'),
);
console.log(`Wrote src/connect/agent.generated.ts (${bundle.text.length} bytes, build ${bundle.build}, sha256 ${bundle.sha256})`);
