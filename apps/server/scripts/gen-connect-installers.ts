// Writes src/connect/install/installers.generated.ts from src/connect/install/scripts/install.{sh,ps1} (docs/prd/targets-connect.md §13),
// after putting the current fetcher (src/connect/install/fetcher.ts) into each script's FETCHER line. The server's bundle carries the
// generated text, so the portal serves exactly what is committed. Run after changing a script or the fetcher, and commit the results
// (src/connect/install/scripts.test.ts fails until then): npm run gen:connect-installers -w @portal/server
import { readFileSync, writeFileSync } from 'node:fs';
import { syncFetcher } from '../src/connect/install/fetcher.js';

const dir = new URL('../src/connect/install/', import.meta.url);
const sh = new URL('scripts/install.sh', dir);
const ps1 = new URL('scripts/install.ps1', dir);

const shText = syncFetcher(readFileSync(sh, 'utf8'), 'sh');
const ps1Text = syncFetcher(readFileSync(ps1, 'utf8'), 'ps1');
writeFileSync(sh, shText);
writeFileSync(ps1, ps1Text);
writeFileSync(
  new URL('installers.generated.ts', dir),
  '// Generated by `npm run gen:connect-installers -w @portal/server` from scripts/install.sh and scripts/install.ps1. Do not edit:\n' +
    '// scripts.test.ts keeps it equal to the scripts.\n' +
    `export const INSTALL_SH = ${JSON.stringify(shText)};\nexport const INSTALL_PS1 = ${JSON.stringify(ps1Text)};\n`,
);
console.log(`Wrote src/connect/install/installers.generated.ts (install.sh ${shText.length} bytes, install.ps1 ${ps1Text.length} bytes)`);
