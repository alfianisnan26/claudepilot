#!/usr/bin/env node
// PILOT-1148: the SPA (the build of apps/web) as cp-next-core's static assets.
//   node scripts/webAssets.mjs      copies ../web/dist into ./public (build it first: `npm run build` here does both) and writes
//                                   public/_headers; prints the file count and bytes, and fails over the Workers asset limits.
// What the asset router serves without the Worker (the shell, a deep link, sw.js, the manifest, icons) gets its headers from
// _headers: the portal's secure headers (apps/server/src/app.ts `appHeaders`: hono secureHeaders, no HSTS, the CSP of
// apps/server/src/csp.ts) and `Cache-Control: no-cache`, so an update reaches installed copies at once. The hashed files
// (/assets/*) go through the Worker (run_worker_first in wrangler.jsonc), which sets their immutable cache and answers a missing
// one with a 404 instead of the shell (src/app.ts). test/assets.test.ts holds the served headers equal to the portal's.
import { createHash } from 'node:crypto';
import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { Hono } from 'hono';
import { secureHeaders } from 'hono/secure-headers';

/** Workers static assets: at most 20,000 files of at most 25 MiB each (Workers Free and Paid). */
export const ASSET_LIMITS = { files: 20_000, fileBytes: 25 * 1024 * 1024 };
/** Files of the assets directory that are not the build's (kept when it is refilled). */
const KEEP = new Set(['.assetsignore']);

/** The hash source of every inline script in a page: the same rule as apps/server/src/csp.ts `inlineScriptHashes`. */
export function inlineScriptHashes(html) {
  const hashes = [];
  for (const m of html.matchAll(/<script(\s[^>]*)?>([\s\S]*?)<\/script>/gi)) {
    if (/\ssrc\s*=/i.test(m[1] ?? '') || !m[2]?.trim()) continue;
    hashes.push(`'sha256-${createHash('sha256').update(m[2]).digest('base64')}'`);
  }
  return hashes;
}

/** The portal's CSP directives (apps/server/src/csp.ts `contentSecurityPolicy`); test/assets.test.ts fails when they drift. */
export function cspDirectives(indexHtml) {
  return {
    defaultSrc: ["'self'"],
    scriptSrc: ["'self'", ...inlineScriptHashes(indexHtml)],
    styleSrc: ["'self'", "'unsafe-inline'"],
    imgSrc: ["'self'", 'data:', 'blob:'],
    fontSrc: ["'self'", 'data:'],
    connectSrc: ["'self'", 'ws:', 'wss:'],
    workerSrc: ["'self'"],
    manifestSrc: ["'self'"],
    frameSrc: ["'self'"],
    objectSrc: ["'none'"],
    baseUri: ["'self'"],
    formAction: ["'self'"],
    frameAncestors: ["'self'"],
  };
}

/** The headers hono's secureHeaders sets with these options, lowercase names (what a response of the portal carries). */
export async function secureHeadersOf(options) {
  const app = new Hono();
  app.use(secureHeaders(options));
  app.get('*', (c) => c.body(null, 204));
  const res = await app.request('/');
  return Object.fromEntries([...res.headers].filter(([k]) => k !== 'content-type'));
}

/** The _headers file for the assets directory, from the built index.html. */
export async function headersFile(indexHtml) {
  const app = await secureHeadersOf({ strictTransportSecurity: false, contentSecurityPolicy: cspDirectives(indexHtml) });
  const lines = Object.entries({ ...app, 'cache-control': 'no-cache' }).map(([k, v]) => `  ${k}: ${v}`);
  return ['# Generated by apps/core-worker/scripts/webAssets.mjs (PILOT-1148); do not edit.', '/*', ...lines, ''].join('\n');
}

function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, out);
    else out.push(p);
  }
  return out;
}

/** Refills `outDir` with the build in `webDist` and its _headers. Throws when the build is missing or over the asset limits. */
export async function prepareAssets(webDist, outDir) {
  const index = join(webDist, 'index.html');
  if (!existsSync(index)) throw new Error(`no web build at ${webDist} (run: npm run build -w @portal/web)`);
  const files = walk(webDist);
  const big = files.filter((f) => statSync(f).size > ASSET_LIMITS.fileBytes);
  if (big.length) throw new Error(`over the 25 MiB asset limit: ${big.join(', ')}`);
  if (files.length + 1 > ASSET_LIMITS.files) throw new Error(`${files.length} files: over the ${ASSET_LIMITS.files} asset limit`);
  mkdirSync(outDir, { recursive: true });
  for (const name of readdirSync(outDir)) if (!KEEP.has(name)) rmSync(join(outDir, name), { recursive: true, force: true });
  cpSync(webDist, outDir, { recursive: true });
  writeFileSync(join(outDir, '_headers'), await headersFile(readFileSync(index, 'utf8')));
  return { files: files.length, bytes: files.reduce((n, f) => n + statSync(f).size, 0) };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const here = dirname(fileURLToPath(import.meta.url));
  const { files, bytes } = await prepareAssets(join(here, '../../web/dist'), join(here, '../public'));
  console.log(`webAssets: ${files} files, ${bytes} bytes copied to apps/core-worker/public (+ _headers)`);
}
