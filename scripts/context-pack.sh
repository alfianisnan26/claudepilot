#!/usr/bin/env bash
# The context pack (T-292, token economy lever 7): docs/context-pack.md, one file of at most 6k tokens (24,000 bytes, chars/4) that tells a new
# session or sub-agent what it would otherwise re-learn by cat, ls and grep: the Map with a test command per area, the commands, conventions,
# the 20 most-changed files of the 30 days before the anchor commit, lessons from the status files, where things live.
#   scripts/context-pack.sh                   write docs/context-pack.md from the working tree, history as of HEAD (the anchor)
#   scripts/context-pack.sh --stdout          print it instead
#   scripts/context-pack.sh --check [rev]     exit 1 if <rev>'s committed pack is stale (default HEAD; used by scripts/gate.sh)
#   options: --anchor <rev> (write mode; default HEAD)  --repo <dir> (default: the repository of the current folder)
#            --no-path-check (tests on a fixture repository only: skip the check that every path named exists)
# Deterministic: the same tree and anchor give the same bytes. The 30-day window ends at the anchor's committer time, never the wall clock;
# files are ordered by commits (most first), then by path (C collation). The anchor and its time are in the first line. --check regenerates
# from <rev>'s tree and compares; when the anchor's history is not here (a shallow clone, as in the gate Job) the history sections are taken
# from the committed pack and only the rest, the paths and the age are checked. Stale also: the anchor older than 7 days before <rev>.
set -euo pipefail
export LC_ALL=C TZ=UTC

OUT=docs/context-pack.md
CAP=24000 WINDOW_DAYS=30 MAX_AGE_DAYS=7 TOP=20
mode=write rev='' anchor='' repo='' pathcheck=1
while [ $# -gt 0 ]; do
  case $1 in
    --check) mode=check; shift; rev=HEAD; if [ $# -gt 0 ] && [[ $1 != --* ]]; then rev=$1; shift; fi ;;
    --stdout) mode=stdout; shift ;;
    --anchor) anchor=${2:?--anchor <rev>}; shift 2 ;;
    --repo) repo=${2:?--repo <dir>}; shift 2 ;;
    --no-path-check) pathcheck=0; shift ;;
    *) echo "usage: scripts/context-pack.sh [--stdout | --check [rev]] [--anchor rev] [--repo dir]" >&2; exit 2 ;;
  esac
done
repo=${repo:-$(git rev-parse --show-toplevel)}
G() { git -C "$repo" -c core.quotepath=off -c log.showSignature=false "$@"; }
die() { echo "context-pack: $*" >&2; exit 1; }

# The source: <rev>'s tree in check mode, the working tree otherwise.
if [ -n "$rev" ]; then rev=$(G rev-parse --verify "$rev^{commit}") || die "no commit $rev"; fi
rd() { if [ -n "$rev" ]; then G show "$rev:$1" 2>/dev/null; else cat "$repo/$1" 2>/dev/null; fi; }
ex() { if [ -n "$rev" ]; then G cat-file -e "$rev:${1%/}" 2>/dev/null; else [ -e "$repo/$1" ]; fi; }
files() { # the files under a folder, sorted
  if [ -n "$rev" ]; then G ls-tree -r --name-only "$rev" -- "$1"; else G ls-files --cached --others --exclude-standard -- "$1" | while IFS= read -r f; do if [ -e "$repo/$f" ]; then echo "$f"; fi; done; fi | sort -u
}
# Words up to N bytes (never a broken character), backticks dropped so a relative name in a description is not taken for a path.
clip() { tr -d '`' | awk -v n="$1" '{ s = ""; for (i = 1; i <= NF; i++) { if (length(s) + length($i) + 1 > n) { s = s " ..."; break } s = (s == "" ? $i : s " " $i) } print s }'; }

# The anchor: history (hot files, lessons) is read as of this commit.
committed=''
if [ "$mode" = check ]; then
  committed=$(rd "$OUT") || die "stale: $OUT is missing at $(G rev-parse --short "$rev"); run scripts/context-pack.sh and commit it"
  read -r anchor anchor_t < <(printf '%s\n' "$committed" | sed -n '1s/^<!-- context-pack anchor \([0-9a-f]\{40\}\) t=\([0-9]*\) .*/\1 \2/p') || true
  [ -n "${anchor:-}" ] || die "stale: $OUT has no anchor line; run scripts/context-pack.sh and commit it"
else
  anchor=$(G rev-parse --verify "${anchor:-HEAD}^{commit}") || die "no anchor commit"
  anchor_t=$(G log -1 --format=%ct "$anchor")
fi
history=0
if [ "$(G rev-parse --is-shallow-repository)" = false ] && G cat-file -e "$anchor^{commit}" 2>/dev/null; then history=1; fi
[ "$mode" = check ] || [ "$history" = 1 ] || die "the anchor's history is not here (shallow clone?)"

# A section of the committed pack without its heading and the blank lines around it.
section_of() { printf '%s\n' "$committed" | awk -v h="$1" '$0 == h { f = 1; next } f && /^## / { exit } f { a[++n] = $0 } END { i = 1; while (i <= n && a[i] == "") i++; while (n >= i && a[n] == "") n--; for (; i <= n; i++) print a[i] }'; }

header() {
  echo "<!-- context-pack anchor $anchor t=$anchor_t ($(date -u -d "@$anchor_t" +%Y-%m-%dT%H:%MZ)). Generated by scripts/context-pack.sh: do not edit; regenerate and commit. -->"
  echo "# Context pack"
  echo
  echo "Read this first; read a file only when this does not answer. Paths are from the repository root. Deeper: \`docs/dev-context.md\`, \`docs/dev-session.md\`, \`docs/open-items.md\`, \`docs/prd/README.md\`."
}

test_of() { # the test command for a Map path cell
  case $1 in
    apps/server/src/\{*\}) local in=${1#apps/server/src/}; echo "\`(cd apps/server && node --import tsx --test 'src/$in/**/*.test.ts')\`" ;;
    apps/server/src/*) echo "\`(cd apps/server && node --import tsx --test 'src/${1#apps/server/src/}/**/*.test.ts')\`" ;;
    apps/web/*) echo "\`npm test -w @portal/web\` and \`npm run typecheck -w @portal/web\`" ;;
    packages/contracts/*) echo "\`npm run typecheck\` (all three packages read it)" ;;
    deploy/*) echo "none here; after a deploy \`scripts/k3s-status.sh\`" ;;
    scripts/*) echo "their tests are in apps/server/src/qa and src/ci, e.g. \`(cd apps/server && node --import tsx --test src/ci/quiet.test.ts)\`" ;;
    *) echo "\`npm run typecheck\`" ;;
  esac
}

section_map() {
  echo; echo "## Map"; echo
  rd CLAUDE.md | awk '/^## Map/ { f = 1; next } f && /^## / { exit } f && /^\| `/' | while IFS= read -r row; do
    local cell desc
    cell=$(printf '%s' "$row" | awk -F'|' '{ print $2 }' | tr -d '` ' )
    desc=$(printf '%s' "$row" | awk -F'|' '{ print $3 }' | clip 230)
    echo "- \`$cell\`: $desc. Test: $(test_of "$cell")"
  done
}

section_commands() {
  echo; echo "## Commands"; echo
  cat <<'EOF'
Heavy jobs (typecheck, the suite, a build) one at a time: through `scripts/job-run.sh` (a Job in the cluster on a pushed ref) or `flock /tmp/heavy.lock`. Wrap long output in `scripts/quiet.sh` so only one line enters the context.
- Typecheck: `npm run typecheck` (server, web, contracts). Web build: `npm run build -w @portal/web`.
- One server test file: `(cd apps/server && node --import tsx --test src/<area>/<file>.test.ts)`; the suite: `(cd apps/server && npm test)` (Docker tests skip without CLAUDEPILOT_DOCKER_TESTS=1).
- Gate: `scripts/gate-quick.sh` before pushing integration (touched areas only); `scripts/gate.sh [commit]` the release gate on a clean copy; `scripts/gate-job.sh <commit>` the same as a Job.
- UI: `scripts/scratch-portal.sh start 3403` then the browser checks in `tools/qa/` (Chromium over CDP; `tools/qa/with-portal.sh` wraps one); stop it after.
- Deploy: `/deploy` (the pipeline `.pilot/deploy.yml`, the owner approves the release). Slash commands: `.claude/commands/`.
- This pack: `scripts/context-pack.sh` (regenerate and commit after a merge; the gate fails on a stale pack).
EOF
  echo
  echo "Scripts:"
  files scripts | grep -E '^scripts/[^/]+\.sh$' | while IFS= read -r f; do
    echo "- \`$f\`: $(rd "$f" | sed -n '2s/^# *//p' | clip 170)"
  done
  echo
  echo "Browser and API checks in \`tools/qa/\`: $(files tools/qa | grep -E '^tools/qa/[^/]+\.(mjs|mts|sh)$' | sed 's#^tools/qa/##' | tr '\n' ' ' | sed 's/ $//')."
}

section_conventions() {
  echo; echo "## Conventions"; echo
  cat <<'EOF'
- Charter and standing decisions bind every agent: `docs/dev-sessions/CHARTER.md`, `docs/dev-sessions/DECISIONS.md`. Token rules: `docs/dev-sessions/token-discipline.md`.
- Authz seam: every route and MCP tool goes through `actorOf` and one `can()` (`apps/server/src/authz`), declared in the module's own `authz.ts`; a denial is the same 404 as not found.
- Secrets: never in a log, response, audit row or transcript (`apps/server/src/chat/redact.ts`); no token-shaped literal anywhere, build test fixtures at runtime. Outbound calls go through the SSRF guard.
- Migrations are append only, numbered by area: `apps/server/src/store/migrations.ts`, numbers in `docs/coord/PLAN.md`, the `/new-migration` command.
- Commits: small, what and why, trailers `Ticket: T-<n>`, `Pilot-Session: <id>`, `Pilot-Agent: <label>`. Work on `integration`; pushing `main` deploys. Never force-push or skip hooks.
- Tests: new behaviour has a test, a fix has the test that fails without it; no fixed dates on the real clock.
- UI: `docs/coord/QA-STANDARDS.md` A1-A9: 44 px targets, no horizontal scroll, 390 px first then 1280, light and dark. Text diet: titles of one or two words, explanations in an InfoTip, icons only on phones.
- Phone rules: no rubber-band (overscroll-behavior), full-screen pages pinned (`apps/web/src/lib/viewport.ts`), sheet headers are not drag handles (`apps/web/src/lib/sheetDrag.ts`), a stale scroll lock heals (`apps/web/src/lib/scrollGuard.ts`); checked by `tools/qa/scroll-lock.mjs` and `tools/qa/mobile-drag.mjs`.
EOF
}

section_where() {
  echo; echo "## Where things live"; echo
  local all
  all=$(files apps/server/src)
  echo "- Server routes: \`apps/server/src/<area>/routes.ts\`, mounted in \`apps/server/src/app.ts\`; areas: $(printf '%s\n' "$all" | sed -n 's#^apps/server/src/\([^/]*\)/routes\.ts$#\1#p' | tr '\n' ' ' | sed 's/ $//')."
  echo "- Authz per area (\`authz.ts\`): $(printf '%s\n' "$all" | sed -n 's#^apps/server/src/\([^/]*\)/authz\.ts$#\1#p' | tr '\n' ' ' | sed 's/ $//')."
  echo "- Wire types and route tables: \`packages/contracts/src\` ($(files packages/contracts/src | sed -n 's#^packages/contracts/src/\([^/]*\)\.ts$#\1#p' | tr '\n' ' ' | sed 's/ $//'))."
  echo "- Web features: \`apps/web/src/features\` ($(files apps/web/src/features | sed -n 's#^apps/web/src/features/\([^/]*\)/.*#\1#p' | sort -u | tr '\n' ' ' | sed 's/ $//')); shared \`apps/web/src/components\`, helpers \`apps/web/src/lib\`."
  echo "- Product documents: \`docs/prd\`; open work: \`docs/open-items.md\`; status files: \`docs/dev-sessions/status\`."
}

describe() { # one line about a file: its first comment or heading, else what it exports
  local d
  d=$(rd "$1" | head -n 12 | awk '
    NR == 1 && /^#!/ { next }
    /^[ \t]*(\/\/|#|\/\*|\*|<!--)/ { sub(/^[ \t]*(\/\/+|#+|\/\*+|\*+|<!--)[ \t]*/, ""); sub(/[ \t]*(\*\/|-->)[ \t]*$/, ""); if ($0 != "") { print; exit } }' | clip 150)
  [ -n "$d" ] || d=$(rd "$1" | sed -nE 's/^export (default )?(async )?(function\*?|const|let|class|interface|type|enum) ([A-Za-z0-9_$]+).*/\4/p' | head -n 6 | tr '\n' ' ' | sed -E 's/ $//; s/^(.+)$/exports \1/')
  printf '%s' "$d"
}

section_hot() {
  echo; echo "## Hot files"; echo
  if [ "$history" = 0 ]; then section_of "## Hot files"; return; fi
  local since=$(( anchor_t - WINDOW_DAYS * 86400 ))
  echo "Most commits in the $WINDOW_DAYS days before the anchor (merges and status files left out):"
  G log "$anchor" --no-merges --no-renames --format='@%ct' --name-only \
    | awk -v since="$since" '/^@/ { t = substr($0, 2) + 0; next } NF && t >= since { n[$0]++ } END { for (f in n) print n[f], f }' \
    | grep -vE ' (docs/context-pack\.md|docs/dev-sessions/status/.*|docs/coord/.*|.*package-lock\.json)$' \
    | sort -k1,1nr -k2,2 | while read -r count f; do ex "$f" && echo "$count $f" || true; done | head -n "$TOP" \
    | while read -r count f; do
        local d; d=$(describe "$f")
        echo "- \`$f\` ($count)${d:+: $d}"
      done
}

section_lessons() {
  echo; echo "## Lessons"; echo
  if [ "$history" = 0 ]; then section_of "## Lessons"; return; fi
  echo "From the LESSONS lines of the status files as of the anchor:"
  local found
  found=$(G ls-tree -r --name-only "$anchor" -- docs/dev-sessions/status | grep -E '\.md$' | sort | while IFS= read -r f; do
    G show "$anchor:$f" | sed -n 's/^LESSONS[^:]*: *//p' | awk '{ n = split($0, a, /; /); for (i = 1; i <= n; i++) { s = a[i]; sub(/[ .]+$/, "", s); if (s != "") print s } }'
  done | awk '!seen[$0]++' | head -n 25 | clip 230 | sed 's/^/- /')
  if [ -n "$found" ]; then printf '%s\n' "$found"; else echo "- none recorded"; fi
}

generate() {
  header; section_map; section_commands; section_conventions; section_where; section_hot; section_lessons
}

pack=$(generate)
bytes=$(printf '%s\n' "$pack" | wc -c)
[ "$bytes" -le "$CAP" ] || die "the pack is $bytes bytes, over the cap of $CAP (6k tokens); shorten a section"
# No secret-shaped text (kept as patterns, not literals).
if printf '%s\n' "$pack" | grep -qE 'gh[pousr]_[A-Za-z0-9]{20,}|github_pat_[A-Za-z0-9_]{20,}|sk-ant-[A-Za-z0-9_-]{10,}|sk-[A-Za-z0-9]{32,}|AKIA[0-9A-Z]{16}|xox[abprs]-[A-Za-z0-9-]{10,}|glpat-[A-Za-z0-9_-]{20,}|-----BEGIN [A-Z ]*PRIVATE KEY|eyJ[A-Za-z0-9_-]{10,}\.eyJ'; then
  die "secret-shaped text in the pack; find it in the sources (the status files?) and remove it there"
fi
if [ "$pathcheck" = 1 ]; then
  missing=$(printf '%s\n' "$pack" | grep -oE '`[^` ]*/[^` ]*`' | tr -d '`' | grep -vE '[*<>()]|^/|^[-.]*$|^https?:' | sort -u | while IFS= read -r p; do
    if [[ $p =~ ^(.*)\{([^}]*)\}(.*)$ ]]; then
      IFS=, read -ra alts <<< "${BASH_REMATCH[2]}"; for a in "${alts[@]}"; do ex "${BASH_REMATCH[1]}$a${BASH_REMATCH[3]}" || echo "${BASH_REMATCH[1]}$a${BASH_REMATCH[3]}"; done
    else ex "$p" || echo "$p"; fi
  done)
  [ -z "$missing" ] || die "stale: paths named in the pack do not exist: $(echo $missing)"
fi

case $mode in
  stdout) printf '%s\n' "$pack" ;;
  write) printf '%s\n' "$pack" > "$repo/$OUT"; echo "context-pack: wrote $OUT ($bytes bytes, anchor $(G rev-parse --short "$anchor"))" ;;
  check)
    rev_t=$(G log -1 --format=%ct "$rev")
    [ $(( rev_t - anchor_t )) -le $(( MAX_AGE_DAYS * 86400 )) ] || die "stale: the anchor is more than $MAX_AGE_DAYS days older than $(G rev-parse --short "$rev"); run scripts/context-pack.sh and commit it"
    if [ "$history" = 1 ] && ! G merge-base --is-ancestor "$anchor" "$rev"; then die "stale: the anchor is not an ancestor of $(G rev-parse --short "$rev")"; fi
    if [ "$pack" != "$committed" ]; then
      diff <(printf '%s\n' "$committed") <(printf '%s\n' "$pack") | head -n 20 >&2 || true
      die "stale: $OUT differs from a regeneration at $(G rev-parse --short "$rev")$([ "$history" = 1 ] || echo ' (history sections taken as committed)'); run scripts/context-pack.sh and commit it"
    fi
    echo "context-pack: fresh at $(G rev-parse --short "$rev") ($bytes bytes, anchor $(G rev-parse --short "$anchor")$([ "$history" = 1 ] || echo ', history not checked: shallow'))" ;;
esac
